from abc import ABC, abstractmethod
class AgendaMedicaRepository(ABC):
    @abstractmethod
    def obtener_por_medico_y_fecha(self,medico_id,fecha): ...
    @abstractmethod
    def obtener_por_cita(self,cita_id): ...
    @abstractmethod
    def guardar(self,agenda): ...
class PacienteRepository(ABC):
    @abstractmethod
    def obtener_por_expediente(self,numero): ...
    @abstractmethod
    def buscar_por_telefono(self,telefono): ...
    @abstractmethod
    def agregar(self,paciente): ...
    @abstractmethod
    def siguiente_numero_de_expediente(self): ...
class MedicoRepository(ABC):
    @abstractmethod
    def obtener(self,medico_id): ...
class AseguradoraRepository(ABC):
    @abstractmethod
    def obtener(self,aseguradora_id): ...
class RegistroDeAuditoriaRepository(ABC):
    @abstractmethod
    def agregar(self,registro): ...
